/**
 * বাংলা সংখ্যা সাহায্যকারী
 *
 * একটি সংখ্যাকে স্থানীয় বাংলা সংখ্যায় রূপান্তর করে (০-৯)। চিহ্ন ও দশমিক
 * বিন্দু অপরিবর্তিত থাকে; শুধু অঙ্কগুলো বদলানো হয়। বিশুদ্ধ ফাংশন, সহজে পরীক্ষাযোগ্য।
 */

const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

/** একটি সংখ্যাকে বাংলা সংখ্যায় রূপান্তর করে (যেমন ৩ => "৩", ১০ => "১০")। */
export function toBengaliNumber(value: number): string {
  return String(value).replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)] ?? d);
}
